const fs = require('fs');
const cyclePath = require('path').join(__dirname, '..', 'src', 'data', 'cycle.ts');
let content = fs.readFileSync(cyclePath, 'utf-8');

// For each person in SABUN_MAP, add s field
for (const [name, sabun] of Object.entries(SABUN_MAP)) {
  // Match pattern: n:"이름"} and add s:"사번"
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const regex = new RegExp(`(n:"${escaped}")(})`);
  if (regex.test(content)) {
    content = content.replace(regex, `$1,s:"${sabun}"$2`);
  } else {
    console.log(`NOT FOUND: ${name}`);
  }
}

fs.writeFileSync(cyclePath, content, 'utf-8');
