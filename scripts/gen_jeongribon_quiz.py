DOC_TITLE = "답십리 승무교육 정리본 심화문제"
DOC_NOTE = (
    "ㆍ난이도: 심화 (실무 운영 디테일 적용형)\n"
    "ㆍ출제 범위: 답십리→하남검단산 영업/회송, 마천행 입고, 차량·운전취급 정리\n"
    "ㆍ문항 수: 20문항 · 시험 시간 권장 25분"
)


def add_q(doc, n, q):
    p = doc.add_paragraph()
    r = p.add_run(f"문제 {n}. ")
    r.bold = True
    r.font.size = Pt(11)
    p.add_run(q["q"]).font.size = Pt(11)
    for i, opt in enumerate(q["opts"]):
        po = doc.add_paragraph()
        po.paragraph_format.left_indent = Cm(0.6)
        po.add_run(f"{['①','②','③','④'][i]} {opt}").font.size = Pt(10.5)
    doc.add_paragraph()


def add_a(doc, n, q):
    p = doc.add_paragraph()
    p.add_run(f"문제 {n}. ").bold = True
    rm = p.add_run(f"정답: {['①','②','③','④'][q['ans']]}  ")
    rm.bold = True
    rm.font.color.rgb = RGBColor(0xC0, 0x39, 0x2B)
    p.add_run(f"\n해설: {q['exp']}").font.size = Pt(10.5)


def main():
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "맑은 고딕"
    style.font.size = Pt(11)

    h = doc.add_heading(DOC_TITLE, level=0)
    h.alignment = WD_ALIGN_PARAGRAPH.CENTER

    sub = doc.add_paragraph(DOC_NOTE)
    sub.paragraph_format.space_after = Pt(14)
    for r in sub.runs:
        r.font.size = Pt(10.5)
        r.font.color.rgb = RGBColor(0x55, 0x55, 0x55)

    doc.add_heading("문제지", level=1)
    for i, q in enumerate(QUESTIONS, start=1):
        add_q(doc, i, q)

    doc.add_page_break()
    doc.add_heading("답지 및 해설", level=1)
    doc.add_paragraph("ㆍ각 문항의 정답과 해설 근거를 정리하였습니다.").runs[0].font.size = Pt(10.5)
    doc.add_paragraph()
    for i, q in enumerate(QUESTIONS, start=1):
        add_a(doc, i, q)

    doc.save(OUT_PATH)
    print(f"OK saved: {OUT_PATH} ({len(QUESTIONS)}문항)")


if __name__ == "__main__":
    main()
