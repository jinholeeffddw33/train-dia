DOC_NOTE = "ㆍ난이도: 중상 (조문 적용·다층 판단형)\nㆍ출제 범위: 운전취급규정 제1조 ~ 제107조 (1~30페이지)\nㆍ문항 수: 20문항 · 시험 시간 권장 25분"


def add_q_paragraph(doc, n, q):
    p = doc.add_paragraph()
    run = p.add_run(f"문제 {n}. ")
    run.bold = True
    run.font.size = Pt(11)
    run2 = p.add_run(q["q"])
    run2.font.size = Pt(11)
    for i, opt in enumerate(q["opts"]):
        po = doc.add_paragraph()
        po.paragraph_format.left_indent = Cm(0.6)
        marker = ["①", "②", "③", "④"][i]
        r = po.add_run(f"{marker} {opt}")
        r.font.size = Pt(10.5)
    doc.add_paragraph()  # 빈 줄


def add_a_paragraph(doc, n, q):
    p = doc.add_paragraph()
    r1 = p.add_run(f"문제 {n}. ")
    r1.bold = True
    marker = ["①", "②", "③", "④"][q["ans"]]
    r2 = p.add_run(f"정답: {marker}  ")
    r2.bold = True
    r2.font.color.rgb = RGBColor(0xC0, 0x39, 0x2B)
    r3 = p.add_run(f"\n근거 및 해설: {q['exp']}")
    r3.font.size = Pt(10.5)


def main():
    doc = Document()
    # 기본 폰트
    style = doc.styles["Normal"]
    style.font.name = "맑은 고딕"
    style.font.size = Pt(11)

    # ── 표지 / 헤더 ──
    h = doc.add_heading(DOC_TITLE, level=0)
    h.alignment = WD_ALIGN_PARAGRAPH.CENTER

    sub = doc.add_paragraph(DOC_NOTE)
    sub.paragraph_format.space_after = Pt(14)
    for r in sub.runs:
        r.font.size = Pt(10.5)
        r.font.color.rgb = RGBColor(0x55, 0x55, 0x55)

    # ── 문제지 ──
    doc.add_heading("문제지", level=1)
    for i, q in enumerate(QUESTIONS, start=1):
        add_q_paragraph(doc, i, q)

    # ── 페이지 나눔 ──
    doc.add_page_break()

    # ── 답지 ──
    doc.add_heading("답지 및 해설", level=1)
    doc.add_paragraph("ㆍ각 문항의 정답과 근거 조문·해설을 정리한 시트입니다.").runs[0].font.size = Pt(10.5)
    doc.add_paragraph()
    for i, q in enumerate(QUESTIONS, start=1):
        add_a_paragraph(doc, i, q)

    doc.save(OUT_PATH)
    print(f"OK saved: {OUT_PATH}")
    print(f"  - 문제 수: {len(QUESTIONS)}")


if __name__ == "__main__":
    main()
