def make_section(sec_id, label, color, emoji, items):
    """카테고리 → handbook.json section 형식"""
    content = []
    for idx, item in enumerate(items, 1):
        block = {
            "type": "broadcast",
            "label": item["label"],
            "color": color,
        }
        if "versions" in item:
            block["versions"] = item["versions"]
        else:
            block["text"] = item["text"]
        content.append(block)
    return {
        "id": sec_id,
        "title": f"{emoji} {label}",
        "summary": [f"{len(items)}개 멘트 — 출처: 승무원 방송수첩 (2026.4)"],
        "content": content,
    }

